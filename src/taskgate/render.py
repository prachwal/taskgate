"""Markdown view of the registry (drift-checked by ``render --check``)."""

from __future__ import annotations

from typing import Any

from .config import Config
from .model import phase_of

HEADER_NOTE = "<!-- GENERATED by `taskgate render` from tasks.json. DO NOT EDIT BY HAND. -->"

BADGES = {
    "draft": "draft",
    "planned": "planned",
    "in_progress": "in-progress",
    "in_review": "in-review",
    "blocked": "**blocked**",
    "done": "done",
    "cancelled": "cancelled",
}


def render(data: dict[str, Any], config: Config) -> str:
    """Render the registry as Markdown tables grouped by phase."""
    tasks = [t for t in data.get("tasks", []) if isinstance(t, dict)]
    lines = [f"# {config.title}", "", HEADER_NOTE, ""]
    if not tasks:
        lines += ["_(no tasks)_", ""]
    for phase in sorted({phase_of(t) for t in tasks}):
        group = [t for t in tasks if phase_of(t) == phase]
        done = sum(1 for t in group if t.get("status") == "done")
        label = config.phase_names.get(phase, f"Phase {phase}")
        lines += [f"## {label} ({done}/{len(group)} done)", "", "| ID | Status | Owner | Title |", "| --- | --- | --- | --- |"]
        for t in group:
            info = str(t.get("blocked_reason") or t.get("title", "")).replace("|", "\\|")
            status = str(t.get("status", "?"))
            lines.append(f"| {t.get('id', '?')} | {BADGES.get(status, status)} | {t.get('owner') or '-'} | {info} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
